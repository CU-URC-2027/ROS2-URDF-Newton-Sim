"""
Generate urc_arm.urdf from arm_params.py and print a mass / torque summary.

    python build_urdf.py                 # uses arm_params.py
    python build_urdf.py my_params       # uses my_params.py (copy arm_params.py to try variants)
"""
import math
import sys
from pathlib import Path
from xml.sax.saxutils import escape

import numpy as np

import arm_model as am

COLORS = {
    "tube": "0.20 0.45 0.85 1", "motor": "0.95 0.55 0.10 1", "extra": "0.55 0.55 0.60 1",
    "payload": "0.80 0.65 0.40 0.6", "rover": "0.45 0.45 0.45 1", "post": "0.30 0.30 0.30 1",
    "tcp": "0.10 0.80 0.20 1", "pivot": "0.85 0.15 0.15 1", "wheel": "0.12 0.12 0.12 1",
}


def f(v):
    return " ".join(f"{x:.6g}" for x in v)


def inertial_xml(m, com, I):
    return (f'    <inertial>\n      <origin xyz="{f(com)}" rpy="0 0 0"/>\n      <mass value="{m:.6g}"/>\n'
            f'      <inertia ixx="{I[0,0]:.6g}" ixy="{I[0,1]:.6g}" ixz="{I[0,2]:.6g}" '
            f'iyy="{I[1,1]:.6g}" iyz="{I[1,2]:.6g}" izz="{I[2,2]:.6g}"/>\n    </inertial>\n')


def geom_xml(tag, name, xyz, geom, color, rpy=(0, 0, 0)):
    mat = f'\n      <material name="{color}"/>' if tag == "visual" else ""
    return (f'    <{tag} name="{escape(name)}">\n      <origin xyz="{f(xyz)}" rpy="{f(rpy)}"/>\n'
            f'      <geometry>{geom}</geometry>{mat}\n    </{tag}>\n')


def box(s):
    return f'<box size="{f(s)}"/>'


def part_visuals(p):
    k = p["kind"]
    if k == "wiring":
        return ""
    if k == "motor":
        r, l = p["size"]
        rpy = {"y": (math.pi / 2, 0, 0), "x": (0, math.pi / 2, 0)}.get(p["axis"], (0, 0, 0))
        return geom_xml("visual", p["name"], p["com"], f'<cylinder radius="{r:.6g}" length="{l:.6g}"/>', k, rpy)
    return geom_xml("visual", p["name"], p["com"], box(p["size"]), k, p.get("rpy", (0, 0, 0)))


def link_name(P, body):
    """URDF link name of a body (the base is a carriage or a turntable)."""
    if body == "base":
        return "carriage" if am.base_slides(P) else "turntable"
    return body


ROVER_JOINTS = ("rover_x", "rover_y", "rover_yaw")


def build(P, mobile=False):
    """Return the URDF as a string. mobile=True adds planar joints (rover_x, rover_y,
    rover_yaw) between base_link and the rover so the sim can drive it."""
    parts = am.body_parts(P)
    inert = am.body_inertials(P, parts)
    org = am.joint_origins(P)
    out = ['<?xml version="1.0"?>\n',
           '<!-- GENERATED by build_urdf.py from arm_params.py. Edit the params, not this file. -->\n',
           '<robot name="urc_arm">\n']
    for name, rgba in COLORS.items():
        out.append(f'  <material name="{name}"><color rgba="{rgba}"/></material>\n')

    # ---- rover (fixed root)
    rg = am.rover_geom(P)
    cx, cy = rg["center"]
    rover_c = (cx, cy, (rg["clearance"] + rg["deck"]) / 2)
    rover_s = (rg["length"], rg["width"], rg["deck"] - rg["clearance"])
    post_len = max(am.base_height(P) - rg["deck"], 0.01)
    C = P.CHASSIS
    rover_com = (cx + C["com"][0], cy + C["com"][1], C["com"][2])
    m = C["mass"]
    rover_I = np.diag([m * (rover_s[1] ** 2 + rover_s[2] ** 2), m * (rover_s[0] ** 2 + rover_s[2] ** 2),
                       m * (rover_s[0] ** 2 + rover_s[1] ** 2)]) / 12.0
    slide = am.base_slides(P)
    # massless root (ROS convention; KDL ignores inertia on the root link)
    out.append('  <link name="base_link"/>\n')
    if mobile:
        chain = [("rover_x", "prismatic", "1 0 0", "rover_x_link"), ("rover_y", "prismatic", "0 1 0", "rover_y_link"),
                 ("rover_yaw", "revolute", "0 0 1", "rover")]
        parent = "base_link"
        for name, jtype, axis, child in chain:
            lim = 50.0 if jtype == "prismatic" else 4 * math.pi
            out.append(f'  <joint name="{name}" type="{jtype}">\n    <parent link="{parent}"/>\n'
                       f'    <child link="{child}"/>\n    <origin xyz="0 0 0" rpy="0 0 0"/>\n'
                       f'    <axis xyz="{axis}"/>\n    <limit lower="{-lim:.6g}" upper="{lim:.6g}" effort="1e5" velocity="10"/>\n'
                       f'  </joint>\n')
            if child != "rover":
                out.append(f'  <link name="{child}">\n' + inertial_xml(1.0, (0, 0, 0), np.eye(3) * 0.1) + '  </link>\n')
            parent = child
    else:
        out.append('  <joint name="base_to_rover" type="fixed">\n    <parent link="base_link"/>\n'
                   '    <child link="rover"/>\n    <origin xyz="0 0 0" rpy="0 0 0"/>\n  </joint>\n')
    out.append('  <link name="rover">\n')
    out.append(inertial_xml(m, rover_com, rover_I))
    out.append(geom_xml("visual", "rover_body", rover_c, box(rover_s), "rover"))
    out.append(geom_xml("collision", "rover_body", rover_c, box(rover_s), "rover"))
    rad = P.WHEELS["diameter"] / 2
    for nm, w in zip(am.WHEEL_NAMES, am.wheel_points(P)):      # wheels (visual only)
        out.append(geom_xml("visual", f"wheel_{nm}", (w[0], w[1], rad),
                            f'<cylinder radius="{rad:.6g}" length="0.08"/>', "wheel", (math.pi / 2, 0, 0)))
    if slide:   # rail on the deck; the post rides on the carriage (drawn on the base link)
        lo_s, hi_s, _, _ = am.joint_limits(P, "base")
        out.append(geom_xml("visual", "rail", (0, (lo_s + hi_s) / 2, rg["deck"] + 0.01),
                            box((0.06, hi_s - lo_s + 0.2, 0.02)), "post"))
    else:
        out.append(geom_xml("visual", "mount_post", (0, 0, rg["deck"] + post_len / 2),
                            f'<cylinder radius="0.04" length="{post_len:.6g}"/>', "post"))
    for p in parts["rover"]:
        out.append(part_visuals(p))
    out.append('  </link>\n')

    # ---- moving bodies
    parent = "rover"
    for j, body in zip(am.JOINT_ORDER, am.BODY_ORDER):
        lo, hi, eff, vel = am.joint_limits(P, j)
        jtype = "prismatic" if am.is_prismatic(P, j) else "revolute"
        link = link_name(P, body)
        out.append(f'  <joint name="{am.joint_name(P, j)}" type="{jtype}">\n    <parent link="{parent}"/>\n'
                   f'    <child link="{link}"/>\n    <origin xyz="{f(org[j])}" rpy="0 0 0"/>\n'
                   f'    <axis xyz="{f(am.joint_axis(P, j))}"/>\n'
                   f'    <limit lower="{lo:.6g}" upper="{hi:.6g}" effort="{eff:.6g}" velocity="{vel:.6g}"/>\n'
                   f'  </joint>\n')
        bi = inert[body]
        out.append(f'  <link name="{link}">\n')
        if body == "base" and slide:
            out.append(geom_xml("visual", "mount_post", (0, 0, -post_len / 2),
                                f'<cylinder radius="0.04" length="{post_len:.6g}"/>', "post"))
        out.append(inertial_xml(bi["mass"], bi["com"], bi["inertia"]))
        if j in ("shoulder", "elbow", "wrist_pitch"):   # red marker on the pitch axis
            out.append(geom_xml("visual", f"{j}_axis", (0, 0, 0),
                                '<cylinder radius="0.008" length="0.08"/>', "pivot", (math.pi / 2, 0, 0)))
        for p in parts[body]:
            out.append(part_visuals(p))
            if p["kind"] in ("tube", "payload"):
                out.append(geom_xml("collision", p["name"], p["com"], box(p["size"]), p["kind"],
                                    p.get("rpy", (0, 0, 0))))
        out.append('  </link>\n')
        parent = link

    # ---- TCP marker
    out.append(f'  <joint name="tcp_joint" type="fixed">\n    <parent link="gripper"/>\n    <child link="tcp"/>\n'
               f'    <origin xyz="{P.L_GRIPPER:.6g} 0 0" rpy="0 0 0"/>\n  </joint>\n')
    out.append('  <link name="tcp">\n')
    out.append(inertial_xml(1e-4, (0, 0, 0), np.eye(3) * 1e-8))
    out.append(geom_xml("visual", "tcp", (0, 0, 0), '<sphere radius="0.012"/>', "tcp"))
    out.append('  </link>\n</robot>\n')
    return "".join(out)


def summary(P):
    inert = am.body_inertials(P)
    kind = "slide along Y" if am.base_slides(P) else "yaw turntable"
    lo, hi, _, _ = am.joint_limits(P, "base")
    rng = f"{lo:+.3f} to {hi:+.3f} m" if am.base_slides(P) else f"{math.degrees(lo):+.0f} to {math.degrees(hi):+.0f} deg"
    print(f"\nBase: {kind} ({rng}). Shoulder axis height {am.shoulder_height(P):.4f} m, "
          f"arm plane offset {am.lateral_offset(P):+.4f} m (Y)")
    for link in am.TUBE_LINKS:
        g = am.link_geometry(P, link)
        print(f"  {link}: pivot-to-pivot {am.link_length(P, link):.3f} m, tube {g['T']:.3f} m, "
              f"tube tilt {math.degrees(g['gamma']):+.2f} deg from the pivot line")
    print("\nBody masses (kg) and COM in each body's frame (m):")
    total = 0.0
    for b in am.BODY_ORDER:
        bi = inert[b]
        total += bi["mass"]
        tag = "  (COM override)" if b in P.COM_OVERRIDE else ""
        print(f"  {b:10s} {bi['mass']:7.3f}   COM {f(np.round(bi['com'], 4))}{tag}")
    print(f"  {'moving':10s} {total:7.3f}   (rover-mounted parts excluded)")

    poses = {
        "home (HOME_DEG)": am.home_q(P),
        "straight out, level": [0, 0, 0, 0, 0],
        "straight out, gripper down": [0, 0, 0, -math.pi / 2, 0],
    }
    names = [am.joint_name(P, j) for j in am.JOINT_ORDER]
    eff = [am.joint_limits(P, j)[2] for j in am.JOINT_ORDER]
    print("\nStatic holding torques (N*m; N for a slide) " + "  ".join(f"{n:>11s}" for n in names))
    for name, q in poses.items():
        tau = am.static_torques(P, q, inert)
        flags = ["*" if abs(t) > e else " " for t, e in zip(tau, eff)]
        print(f"  {name:40s}  " + "  ".join(f"{t:10.2f}{fl}" for t, fl in zip(tau, flags)))
    print(f"  {'effort limit':40s}  " + "  ".join(f"{e:10.2f} " for e in eff))
    print("  (* = above the joint's effort limit; the sim arm will sag there)")

    S = P.SLOPE
    print(f"\nTipping (rover {P.CHASSIS['mass']} kg, wheelbase {P.WHEELS['wheelbase']} m, track {P.WHEELS['track']} m, "
          f"slope {S['deg']} deg, braking/turning {P.DRIVE_ACCEL} m/s^2)")
    print(f"  {'pose':32s}  {'margin still':>14s}  {'margin driving':>15s}  wheel loads FL FR RL RR (N)")
    for name, q in poses.items():
        st = am.stability(P, q, None, inert)
        wd = am.worst_drive(P, q, None, inert)
        print(f"  {name:32s}  {st['margin']:7.3f} {st['edge']:>6s}  {wd['margin']:8.3f} {wd['edge']:>6s}  "
              + " ".join(f"{n:6.0f}" for n in st["N"]))
    print("  (margin = centre of pressure to the nearest wheel-footprint edge; negative = tips over)")


def write(P, folder=None):
    path = Path(folder or Path(__file__).parent) / P.URDF_FILE
    path.write_text(build(P))
    return path


def main():
    P = am.load_params(sys.argv[1] if len(sys.argv) > 1 else "arm_params")
    print(f"Wrote {write(P)}")
    summary(P)


if __name__ == "__main__":
    main()
